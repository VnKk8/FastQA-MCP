import { promises as fs } from 'node:fs';
import path from 'node:path';
import { Session, type RecordedStep } from './session.js';
import { runStep, bind } from './runner.js';

export const FLOW_DIR = () => path.resolve(process.env.FASTQA_DIR || path.join(process.cwd(), '.fastqa'));
const flowPath = (name: string) => path.join(FLOW_DIR(), 'flows', `${safe(name)}.json`);
const safe = (n: string) => n.replace(/[^\w.-]+/g, '-').slice(0, 80);

export interface Flow {
  name: string;
  created: string;
  steps: RecordedStep[];
}

export async function saveFlow(name: string, steps: RecordedStep[]): Promise<string> {
  const p = flowPath(name);
  await fs.mkdir(path.dirname(p), { recursive: true });
  const flow: Flow = { name, created: new Date().toISOString(), steps };
  await fs.writeFile(p, JSON.stringify(flow, null, 2));
  return p;
}

export async function loadFlow(name: string): Promise<Flow> {
  return JSON.parse(await fs.readFile(flowPath(name), 'utf8'));
}

export async function listFlows(): Promise<string[]> {
  try {
    return (await fs.readdir(path.join(FLOW_DIR(), 'flows'))).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
  } catch { return []; }
}

export interface FlowRun { name: string; ok: boolean; ms: number; lines: string[]; failedAt?: number; evidence: string[]; screenshot?: string; shotFile?: string; url?: string; started: string }

/** Replays a flow in its own isolated browser context. No model involved. */
export async function runFlow(name: string, vars: Record<string, string> = {}, shared?: Session): Promise<FlowRun> {
  const flow = await loadFlow(name);
  const s = new Session();
  if (shared?.browser) s.browser = shared.browser; // reuse the running browser process, new context
  const t0 = Date.now();
  const started = new Date().toISOString();
  const lines: string[] = [];
  let ok = true; let failedAt: number | undefined;
  let screenshot: string | undefined; let shotFile: string | undefined; let url: string | undefined;
  try {
    await s.ensure();
    s.mark = Date.now();
    for (let i = 0; i < flow.steps.length; i++) {
      const step = flow.steps[i];
      const r = await runStep(s, bind(step, vars), step);
      lines.push(`${String(i + 1).padStart(2)}. ${r.line}`);
      if (!r.ok) { ok = false; failedAt = i + 1; break; }
      if (/^(goto|click|dblclick|press|select|check|uncheck)$/.test(step.do)) await s.settle(1500);
    }
  } catch (e: any) {
    ok = false; lines.push(`✗ ${String(e?.message || e).split('\n')[0]}`);
  }
  if (!ok && s.page && !s.page.isClosed()) {
    try {
      url = s.page.url();
      const buf = await s.page.screenshot({ type: 'jpeg', quality: 60 });
      screenshot = buf.toString('base64');
      shotFile = path.join(FLOW_DIR(), 'artifacts', `${safe(name)}-${Date.now()}.jpg`);
      await fs.mkdir(path.dirname(shotFile), { recursive: true });
      await fs.writeFile(shotFile, buf);
    } catch { /* page gone */ }
  }
  const ev = s.takeEvidence();
  const evidence = [...ev.pageErrors.map((x) => 'pageerror: ' + x), ...ev.console.filter((x) => x.startsWith('[error]')), ...ev.failedRequests];
  if (shared?.browser) await s.closeContext(); else await s.close();
  return { name, ok, ms: Date.now() - t0, lines, failedAt, evidence, screenshot, shotFile, url, started };
}

/** Exports a flow as a Playwright Test spec. */
export async function exportFlow(name: string): Promise<{ file: string; code: string }> {
  const flow = await loadFlow(name);
  const body = flow.steps.map((s) => '  ' + (s.code ?? `// ${s.do} ${s.target ?? ''} ${s.value ?? ''}`)).join('\n');
  const code = `import { test, expect } from '@playwright/test';

// Generated by fastqa-mcp from flow "${flow.name}" (${flow.created})
// Templated values read FASTQA_VAR_<name> environment variables.
test(${JSON.stringify(flow.name)}, async ({ page }) => {
${body}
});
`;
  const file = path.join(FLOW_DIR(), 'tests', `${safe(name)}.spec.ts`);
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, code);
  return { file, code };
}

/** Reads a CSV data file (header row = variable names). Looks in .fastqa/data/<name>.csv when given a bare name. */
export async function loadDataset(nameOrPath: string): Promise<Record<string, string>[]> {
  const p = /[\\/]|\.csv$/i.test(nameOrPath) ? path.resolve(nameOrPath) : path.join(FLOW_DIR(), 'data', `${safe(nameOrPath)}.csv`);
  const rows = (await fs.readFile(p, 'utf8')).split(/\r?\n/).filter((l) => l.trim()).map(splitCsv);
  const [head, ...data] = rows;
  return data.map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? '').trim()])));
}
function splitCsv(line: string): string[] {
  const out: string[] = []; let cur = ''; let inQ = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (inQ) { if (c === '"' && line[i + 1] === '"') { cur += '"'; i++; } else if (c === '"') inQ = false; else cur += c; }
    else if (c === '"') inQ = true; else if (c === ',') { out.push(cur); cur = ''; } else cur += c;
  }
  out.push(cur); return out;
}

/** Runs flows, optionally once per dataset row, then writes an HTML report and a JUnit XML file. */
export async function runSuite(names: string[], vars: Record<string, string>, dataset?: string, shared?: Session) {
  const rows = dataset ? await loadDataset(dataset) : [{}];
  const runs: FlowRun[] = [];
  for (const n of names) {
    for (let i = 0; i < rows.length; i++) {
      const r = await runFlow(n, { ...vars, ...rows[i] }, shared);
      if (dataset) r.name = `${n} [row ${i + 1}: ${Object.entries(rows[i]).filter(([k]) => !/pass|pwd|secret|token|key|card|cc/i.test(k)).map(([, v]) => v).join(', ').slice(0, 40)}]`;
      runs.push(r);
    }
  }
  const { writeReports } = await import('./report.js');
  const files = await writeReports(runs, FLOW_DIR());
  return { runs, ...files };
}
